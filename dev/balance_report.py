"""Balance report: what each preset does at every stage of the game, without building a pak.

For chapters 0..32 it assumes a party at the story's recommended level ("on pace") or 15
levels above it ("over-levelled"), and reports the world floor, how much the enemies of the
areas you'd be in change, and how a boss of the chapter you'd be doing is scaled.

    python dev/balance_report.py  > docs/BALANCE.md
"""
import os
import statistics
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))
import pak                                  # noqa: E402
import paths                                # noqa: E402
import uasset                               # noqa: E402
import config                               # noqa: E402
import build_difficulty_mod as B            # noqa: E402

g = B.g


def main():
    p = pak.Pak(paths.base_pak())
    rows = uasset.read_datatable(p.read(B.ENEMY + ".uasset"), p.read(B.ENEMY + ".uexp"))
    bosses, _s = B.boss_sets(p)
    curve, levels = B.build_curve(rows, bosses)
    cls = B.enemy_classes(p, rows)
    natives = B.boss_natives(p, rows, cls, curve, levels)

    # each random enemy's home danger = the highest area danger it appears at
    def T(path):
        return uasset.read_datatable(p.read(path + ".uasset"), p.read(path + ".uexp"))
    eg, be, vol = T(B.ENEMY_GROUPS), T(B.ENCOUNTERS), T(B.VOLUME)
    home = {}
    for v in vol.values():
        for e in g(v, "EncounterList"):
            d, n = g(e, "DangerLevel"), g(e, "EncounterName")
            for x in (g(be[n], "Group") if n in be else []):
                for en in (g(eg[g(x, "GroupID")], "EnemyID") if g(x, "GroupID") in eg else []):
                    home[en] = max(home.get(en, 0), d)
    rand = [k for k in rows if cls[k] == "random" and k in home]

    def area_effect(floor, story, lo, hi):
        """median HP multiplier on enemies whose home danger is in story+[lo, hi]"""
        if not B.FLOOR_ACTIVE:              # opening stage: regular enemies as shipped
            return 1.0
        near = [k for k in rand if story + lo <= home[k] <= story + hi]
        P = B.profile_at(curve, levels, floor)
        mult = [max(1.0, P["HP"] / max(1, g(g(rows[k], "Param"), "HP"))) for k in near]
        return statistics.median(mult) if mult else 1.0

    def boss_effect(floor, chapter_native):
        n = B.profile_at(curve, levels, chapter_native)
        t = B.profile_at(curve, levels, floor)
        return max(1.0, t["HP"] / n["HP"]) * B.BOSS_HP_MULT, max(1.0, t["ATK"] / n["ATK"])

    print("# Balance report\n")
    print("Generated by `dev/balance_report.py` from the game's own data. *Story danger* is the "
          "game's recommended level for the chapters you'd be on. *Enemies* is the median HP "
          "multiplier on random enemies of the areas you'd be in (home danger within 3 of the "
          "story's) / of older areas (6+ below), which are raised on purpose. Every preset opens "
          "as vanilla and reaches the values in overhaul.ini by the mid game (stage ramp). *Chapter boss* is the HP / Atk "
          "multiplier on a boss of the chapter you'd be doing, fought then.\n")
    for preset in config.PRESETS:
        cfg = config.load()
        cfg.update(config.PRESETS[preset])
        cfg["preset"] = preset
        config.apply(cfg)
        print(f"\n## {preset}\n")
        print("| Chapters | Story danger | Party (on pace) | Floor | Enemies | Chapter boss "
              "HP / Atk | Party (+15) | Floor | Enemies | Boss HP / Atk |")
        print("|---|---|---|---|---|---|---|---|---|---|")
        for c in range(0, 33, 4):
            story = B.expected_danger(c)
            # the chapter you'd be doing next: its recommended level is the story danger
            out = [str(c), f"{story:.0f}"]
            for extra in (0, 15):
                party = round(story + extra)
                floor, _w = B.world_floor(c * B.PROGRESS_PER_QUEST, party)
                hp, atk = boss_effect(floor, story)
                out += [str(party), str(floor),
                        f"x{area_effect(floor, story, -3, 3):.2f} / "
                        f"x{area_effect(floor, story, -99, -6):.2f}",
                        f"x{hp:.2f} / x{atk:.2f}"]
            print("| " + " | ".join(out) + " |")
        print()
        sup = [k for k in rows if cls[k] == "super"]
        for floor in (50, 60, 70, 80, 99):
            scaled = sum(1 for k in sup if natives[k] < floor)
            extra = B.settings_at(floor)["superboss_hp_mult"] if B.RAMP else B.SUPERBOSS_HP_MULT
            print(f"- world danger {floor}: {scaled}/{len(sup)} superboss rows above their "
                  f"native danger get scaled (extra HP x{extra:g})")


if __name__ == "__main__":
    main()
